namespace PsoBB.Text;

/// <summary>
/// The horizontal placement of each laid-out line inside the available width.
/// </summary>
public enum TextAlignment
{
	/// <summary>Lines start at the left edge.</summary>
	Left,
	/// <summary>Lines are centred in the available width.</summary>
	Center,
	/// <summary>Lines end at the right edge.</summary>
	Right,
}
