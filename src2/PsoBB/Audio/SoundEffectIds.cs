	/// <summary>
	/// Returns the loaded slot a global sound-effect identifier selects.
	/// </summary>
	/// <param name="soundEffectId">The global identifier.</param>
	/// <param name="area">The client's current area, or -1 when it is unknown.</param>
	/// <returns>The slot, or -1 when the identifier is outside the client table.</returns>
	public static int SlotFor(int soundEffectId, int area = -1)
	{
		if (soundEffectId <= 0 || soundEffectId >= SlotCount)
			return -1;
		if ((area == WaterArea || area == WildsArea) && soundEffectId >= SelectionId && soundEffectId <= SelectionId + 3)
			return SelectionSlot + soundEffectId - SelectionId;
		return Remaps.GetValueOrDefault(soundEffectId, soundEffectId);
	}

	/// <summary>
	/// Returns the attenuation index stored for a loaded slot.
	/// </summary>
	/// <param name="slot">The slot.</param>
	/// <returns>The index from zero through 127, or zero outside the table.</returns>
	public static int VolumeIndex(int slot) => (uint)slot < SlotCount ? Attenuation[slot] : 0;

	/// <summary>
	/// Converts an attenuation index to DirectSound hundredths of a decibel.
	/// </summary>
	/// <param name="volumeIndex">The index from zero through 127.</param>
	/// <returns>The volume in hundredths of a decibel, from zero down to -6400.</returns>
	public static int VolumeCentibels(int volumeIndex)
	{
		int index = Math.Clamp(volumeIndex, 0, 127);
		double attenuation = -index / 127.0;
		return (int)(6400.0 * attenuation * attenuation * attenuation);
	}

	/// <summary>
	/// Converts an attenuation index to a linear gain.
	/// </summary>
	/// <param name="volumeIndex">The index from zero through 127.</param>
	/// <returns>The gain from one down to the -64-decibel floor.</returns>
	public static float VolumeGain(int volumeIndex) => MathF.Pow(10f, VolumeCentibels(volumeIndex) / 2000f);
