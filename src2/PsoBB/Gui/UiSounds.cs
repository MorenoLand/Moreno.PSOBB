namespace PsoBB.Gui;

/// <summary>
/// The sound-effect identifiers the shared list control plays.
/// </summary>
public static class UiSounds
{
	/// <summary>Played when the selection moves.</summary>
	public const int Select = 1391;

	/// <summary>Played when a row is activated, as the list control does at <c>0x00735134</c>.</summary>
	public const int Activate = 1413;

	/// <summary>Played when the dialog is cancelled, as the list control does at <c>0x00735178</c>.</summary>
	public const int Cancel = 1392;
}
