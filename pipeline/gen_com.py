# gen_com.py: read the MinGW COM headers and emit the vtable slot/argument tables
# used by runtime/com.c to wrap host objects (d3d8, dinput8, dsound) for the guest.
import json
import os
import re
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import cfg

INCLUDE = os.path.join(cfg.mingw32(), "include")
HEADERS = ["d3d8.h", "dinput.h", "dsound.h"]
BASES = {"IUnknown": 3, "IDirect3DResource8": None}
WANT = ["IDirect3D8", "IDirect3DDevice8", "IDirect3DBaseTexture8", "IDirect3DTexture8",
        "IDirect3DVolumeTexture8", "IDirect3DCubeTexture8", "IDirect3DSurface8", "IDirect3DVolume8",
        "IDirect3DVertexBuffer8", "IDirect3DIndexBuffer8", "IDirect3DSwapChain8",
        "IDirectInput8A", "IDirectInput8W",
        "IDirectInputDevice8A", "IDirectInputDevice8W", "IDirectSound", "IDirectSoundBuffer",
        "IDirectSound3DListener", "IDirectSound3DBuffer", "IDirectSoundNotify", "IDirectSound8"]

text = ""
for h in HEADERS:
    p = os.path.join(INCLUDE, h)
    if os.path.exists(p):
        text += open(p, encoding="latin-1").read()

iface_re = re.compile(r"DECLARE_INTERFACE(?:_IID_|_)?\(\s*(\w+)\s*,\s*(\w+)\s*(?:,\s*\"[^\"]*\")?\s*\)\s*\{(.*?)\n\};", re.S)
method_re = re.compile(r"STDMETHOD_?\(\s*(?:[^,()]*,\s*)?(\w+)\s*\)\s*\((.*?)\)\s*PURE", re.S)


def nargs(sig):
    sig = re.sub(r"/\*.*?\*/", "", sig, flags=re.S).strip()
    sig = sig.replace("THIS_", "").replace("THIS", "").strip()
    if not sig or sig == "void":
        return 0
    depth = 0
    parts = 1
    for ch in sig:
        if ch in "([":
            depth += 1
        elif ch in ")]":
            depth -= 1
        elif ch == "," and depth == 0:
            parts += 1
    return parts


found = {}
for m in iface_re.finditer(text):
    name, base = m.group(1), m.group(2)
    methods = [(mm.group(1), nargs(mm.group(2))) for mm in method_re.finditer(m.group(3))]
    if methods:
        found[name] = {"base": base, "methods": methods}
        if name in WANT:
            print("%-24s base %-24s own %d" % (name, base, len(methods)))

out = {}


def offset_of(name):
    if name in out:
        return out[name]["offset"]
    if name == "IUnknown":
        return 3
    if name not in found:
        return None
    if found[name]["methods"][0][0] == "QueryInterface":     # the header restates the base methods
        out[name] = {"offset": 0, "methods": found[name]["methods"]}
        return 0
    b = offset_of(found[name]["base"])
    if b is None:
        return None
    out[name] = {"offset": b + len(found[found[name]["base"]]["methods"]), "methods": found[name]["methods"]}
    return out[name]["offset"]


for name in WANT:
    if name not in found:
        print("missing", name)
        continue
    offset_of(name)

json.dump(out, open(os.path.join(cfg.DATA, "com_interfaces.json"), "w", encoding="utf-8"), indent=1)

import struct as _struct
GUIDE = re.compile(r"DEFINE_GUID\(\s*IID_(\w+)\s*,\s*0x([0-9a-fA-F]+)\s*,\s*0x([0-9a-fA-F]+)\s*,\s*0x([0-9a-fA-F]+)\s*,([^)]*)\)")
iids = []
for _m in GUIDE.finditer(text):
    _name = _m.group(1)
    if _name not in out:
        continue
    _rest = [int(x, 16) & 0xFF for x in _m.group(5).split(",") if x.strip()]
    if len(_rest) != 8:
        continue
    _b = _struct.pack("<IHH", int(_m.group(2), 16), int(_m.group(3), 16), int(_m.group(4), 16)) + bytes(_rest)
    iids.append((_b, _name))
print("iids", len(iids))

with open(os.path.join(cfg.RT, "com_gen.h"), "w", encoding="utf-8") as f:
    f.write("/* generated by gen_com.py: do not edit */\n")
    f.write("#ifndef SS_COM_GEN_H\n#define SS_COM_GEN_H\n\n")
    for name, e in out.items():
        f.write("static const signed char com_%s_nargs[] = {" % name)
        f.write(", ".join(str(n) for _, n in e["methods"]))
        f.write("};\n")
    f.write("\nconst struct { const char *name; int offset; int count; const signed char *nargs; } com_ifaces[] = {\n")
    for name, e in out.items():
        f.write('    {"%s", %d, %d, com_%s_nargs},\n' % (name, e["offset"], len(e["methods"]), name))
    f.write("};\nconst int com_iface_count = %d;\n" % len(out))
    f.write("\nconst struct { unsigned char guid[16]; const char *iface; } com_iids[] = {\n")
    for _g, _n in iids:
        f.write("    {" + ",".join("0x%02x" % _c for _c in _g) + ', "' + _n + '"},\n')
    f.write("};\nconst int com_iid_count = %d;\n\n#endif\n" % len(iids))
print("wrote", os.path.join(cfg.RT, "com_gen.h"))
